import {test, expect} from '../../fixtures';
import {createLiveEventWithFreeTicket, createDraftEvent} from '../../api/factory';
import {CheckoutPage} from '../../pages/checkout.page';
import {SubscribersPage} from '../../pages/subscribers.page';
import {uniqueEmail} from '../../utils/unique';

test('public signup, confirmation, announcement and unsubscribe', {tag: '@smoke'}, async ({freshAccount, page, publicApi, mailpit}) => {
  const api = freshAccount.api;
  const organizerId = freshAccount.organizerId;
  await api.updateOrganizerStatus(organizerId, 'LIVE');
  await api.updateOrganizerSettings(organizerId, {new_event_notifications_enabled: true});
  const event = await createLiveEventWithFreeTicket(api, organizerId);
  const email = uniqueEmail('event-subscriber');
  await page.goto(`/event/${event.eventId}/${event.slug}`);
  await page.getByRole('button', {name: 'Subscribe to new events', exact: true}).click();
  await page.getByRole('dialog').getByRole('textbox', {name: 'Email address'}).fill(email);
  await page.getByRole('dialog').getByRole('button', {name: 'Subscribe', exact: true}).click();
  await expect(page.getByRole('status')).toContainText('Check your email');
  const link = await mailpit.waitForLink(email, /subscriptions\/confirm\//, {subjectContains: 'Confirm your event subscription'});
  await page.goto(link.pathname);
  expect((await api.getOrganizerSubscribers(organizerId)).find(row => row.email === email)?.status).toBe('pending');
  await page.getByRole('button', {name: 'Confirm subscription', exact: true}).click();
  await expect(page.getByRole('status')).toContainText('Subscription confirmed');
  const newEvent = await createDraftEvent(api, organizerId);
  await api.publishEvent(newEvent.eventId);
  const announcement = await mailpit.waitForMessage(email, {subjectContains: 'New event from'});
  const message = await mailpit.getMessage(announcement.ID);
  expect(message.HTML).toContain(newEvent.title);
  const unsubscribe = (await mailpit.getLinks(announcement.ID)).find(url => url.includes('/subscriptions/unsubscribe/'))!;
  await page.goto(new URL(unsubscribe).pathname);
  await page.getByRole('button', {name: 'Unsubscribe', exact: true}).click();
  await expect(page.getByRole('status')).toContainText('You are unsubscribed');
  expect((await api.getOrganizerSubscribers(organizerId)).find(row => row.email === email)?.status).toBe('unsubscribed');
});

test('organizer signup, management, CSV, selection reset, bulk unsubscribe and pause', async ({freshAccount, page, publicApi, mailpit}) => {
  const api = freshAccount.api;
  const organizerId = freshAccount.organizerId;
  await api.updateOrganizerStatus(organizerId, 'LIVE');
  const managementPage = await freshAccount.newAuthedPage();
  await managementPage.goto(`/manage/organizer/${organizerId}/settings#subscribers`);
  await expect(managementPage.getByRole('switch', {name: /^Enable new-event notifications/})).toBeEnabled();
  await managementPage.getByRole('switch', {name: /^Enable new-event notifications/}).press('Space');
  await expect(managementPage.getByRole('switch', {name: /^Enable new-event notifications/})).toBeChecked();
  await expect(managementPage.getByText('Subscription settings updated', {exact: true})).toBeVisible();
  const organizerResponse = await publicApi.get(`public/organizers/${organizerId}`);
  const organizer = (await organizerResponse.json()).data;
  await page.goto(`/events/${organizerId}/${organizer.slug}`);
  const email = uniqueEmail('profile-subscriber');
  await page.getByRole('button', {name: 'Subscribe to new events', exact: true}).first().click();
  await page.getByRole('dialog').getByRole('textbox', {name: 'Email address'}).fill(email);
  await page.getByRole('dialog').getByRole('button', {name: 'Subscribe', exact: true}).click();
  await expect(page.getByRole('status')).toContainText('Check your email');
  const other = uniqueEmail('other-subscriber');
  const response = await publicApi.post(`public/organizers/${organizerId}/event-subscriptions`, {data: {email: other, locale: 'en'}});
  expect(response.ok()).toBeTruthy();
  const subscribers = new SubscribersPage(managementPage);
  await subscribers.goto(organizerId);
  await expect(subscribers.row(email)).toContainText('Pending confirmation');
  await expect(subscribers.row(other)).toBeVisible();
  await managementPage.getByRole('checkbox', {name: 'Select all subscribers on this page'}).check();
  await subscribers.search(email);
  await expect(subscribers.row(other)).toHaveCount(0);
  await expect(managementPage.getByRole('button', {name: 'Unsubscribe selected (0)'})).toBeDisabled();
  const downloadPromise = managementPage.waitForEvent('download');
  await managementPage.getByRole('button', {name: 'Export CSV', exact: true}).click();
  const download = await downloadPromise;
  const stream = await download.createReadStream();
  let csv = '';
  for await (const chunk of stream!) csv += chunk.toString();
  expect(csv).toContain(email);
  expect(csv).not.toContain(other);
  await subscribers.search('');
  await expect(subscribers.row(other)).toBeVisible();
  await managementPage.getByRole('checkbox', {name: 'Select all subscribers on this page'}).check();
  await subscribers.unsubscribeSelected(2);
  await expect(subscribers.row(email)).toContainText('Unsubscribed');
  await expect(subscribers.row(other)).toContainText('Unsubscribed');
  await managementPage.goto(`/manage/organizer/${organizerId}/settings#subscribers`);
  await expect(managementPage.getByRole('switch', {name: /^Enable new-event notifications/})).toBeEnabled();
  await managementPage.getByRole('switch', {name: /^Enable new-event notifications/}).press('Space');
  await expect(managementPage.getByRole('switch', {name: /^Enable new-event notifications/})).not.toBeChecked();
  await expect(managementPage.getByText('Subscription settings updated', {exact: true})).toBeVisible();
  await subscribers.goto(organizerId);
  await expect(managementPage.getByText('Notifications paused', {exact: true})).toBeVisible();
  await page.reload();
  await expect(page.getByRole('button', {name: 'Subscribe to new events', exact: true})).toHaveCount(0);
});

test('checkout opt-in creates a pending subscription after a free purchase', async ({freshAccount, page, mailpit}) => {
  const api = freshAccount.api;
  const organizerId = freshAccount.organizerId;
  await api.updateOrganizerStatus(organizerId, 'LIVE');
  await api.updateOrganizerSettings(organizerId, {new_event_notifications_enabled: true});
  const event = await createLiveEventWithFreeTicket(api, organizerId);
  const email = uniqueEmail('checkout-subscriber');
  const checkout = new CheckoutPage(page);
  await checkout.gotoPublicEvent(event.eventId, event.slug);
  await checkout.setFirstProductQuantity(1);
  await checkout.continueToCheckout();
  const buyer = {firstName: 'Buyer', lastName: 'Person', email};
  await checkout.fillOrderDetails(buyer);
  await checkout.fillFirstAttendee(buyer);
  await page.getByRole('checkbox', {name: /Keep me updated on news and events/}).check();
  await checkout.completeFreeOrder();
  const link = await mailpit.waitForLink(email, /subscriptions\/confirm\//, {subjectContains: 'Confirm your event subscription'});
  await expect.poll(async () => (await api.getOrganizerSubscribers(organizerId)).find(row => row.email === email)?.status).toBe('pending');
  await page.goto(link.pathname);
  await page.getByRole('button', {name: 'Confirm subscription', exact: true}).click();
  await expect(page.getByRole('status')).toContainText('Subscription confirmed');
});
